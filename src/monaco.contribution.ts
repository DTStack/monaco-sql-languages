import { EntityContext, Suggestions } from 'dt-sql-parser';

import type { FormatFallback } from './formatTypes';
import { editor, Emitter, IEvent, IRange, languages, Position } from './fillers/monaco-editor-core';

export type { FormatFallback } from './formatTypes';

/**
 * A completion item.
 * ICompletionItem is pretty much the same as {@link languages.CompletionItem},
 * with the only difference being that the range and insertText is optional.
 */
export interface ICompletionItem extends Omit<languages.CompletionItem, 'range' | 'insertText'> {
	range?: IRange | languages.CompletionItemRanges;
	insertText?: string;
}

/**
 * ICompletionList is pretty much the same as {@link languages.CompletionList},
 * with the only difference being that the type of suggestion is {@link ICompletionItem}
 */
export interface ICompletionList extends Omit<languages.CompletionList, 'suggestions'> {
	suggestions: ICompletionItem[];
}

/**
 * A service to build completions.
 * @param model monaco TextModel which triggers completion
 * @param position location that triggers completion
 * @param completionContext context of completion
 * @param suggestions suggestions for completion
 */
export type CompletionService = (
	model: editor.IReadOnlyModel,
	position: Position,
	completionContext: languages.CompletionContext,
	suggestions: Suggestions | null,
	entities: EntityContext[] | null,
	snippets?: CompletionSnippet[]
) => Promise<ICompletionItem[] | ICompletionList>;

export interface CompletionOptions {
	enable: boolean;
	/**
	 * Define a service to customize  completionItems.
	 * By default, only keyword autocomplete items are included.
	 */
	completionService: CompletionService;
	triggerCharacters: string[];
	snippets: CompletionSnippetOption[];
	/**
	 * Whether to continuously trigger completion after a completion item is accepted.
	 *
	 * If enabled, a command re-triggering the suggest widget is attached to completion items
	 * whose insertion moves the caret into a new syntactic context:
	 * - keyword items without an explicit `insertText` are inserted with a trailing space
	 *   (e.g. `SELECT `), so the next context (columns, `*`, ...) is offered automatically.
	 *   In a function syntax context, keyword items are inserted as-is (no trailing space)
	 *   and do not re-trigger, so the user can type the function's parentheses themselves;
	 * - items whose `insertText` ends with a trigger character re-trigger completion, e.g. a
	 *   custom `completionService` can insert a database as `my_database.` so that tables
	 *   inside it are suggested right away.
	 *
	 * Items defining their own `command` are left untouched, and plain entity items (tables,
	 * columns, ...) do not re-trigger: their context hasn't changed, so the re-triggered
	 * widget would just re-offer the item that was just accepted.
	 *
	 * Defaults to false.
	 */
	continuousCompletion?: boolean;
}

export interface CompletionSnippet {
	prefix: string;
	label: string;
	body: string | string[];
	// generated by body
	insertText?: string;
	description?: string;
}

export type CompletionSnippetOption = Omit<CompletionSnippet, 'insertText'>;

export interface FormatOptions {
	/**
	 * Defines whether the built-in Format action is enabled.
	 * Defaults to false.
	 */
	enable: boolean;
	/**
	 * Called when sql-formatter is unavailable or throws. Should return formatted SQL.
	 */
	fallback?: FormatFallback;
	/**
	 * Indent width passed to sql-formatter. Defaults to 4.
	 * Values below 1 (or non-finite) fall back to 4; fractional values are floored.
	 */
	tabWidth?: number;
	/**
	 * Custom keybindings for the Format action.
	 * Defaults to Ctrl/Cmd+Alt+F.
	 */
	keybindings?: number[];
}

/** Runtime options passed to {@link formatSQL} / {@link formatEditorSQL}. */
export type FormatSQLOptions = Pick<FormatOptions, 'fallback' | 'tabWidth'>;

